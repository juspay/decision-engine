/**
 * Options for a gateway field: names already used elsewhere in the rule first (they are the likely
 * next pick, and may be merchant-specific names absent from the connector list), then every
 * routable connector, minus whatever this field has already collected.
 */
export function gatewayOptions(suggestions: readonly string[], alreadyPicked: readonly string[] = []): string[] {
  const picked = new Set(alreadyPicked.filter(Boolean))
  const seen = new Set<string>()
  return [...suggestions, ...ROUTABLE_CONNECTORS].filter((name) => {
    if (!name || picked.has(name) || seen.has(name)) return false
    seen.add(name)
    return true
  })
}
